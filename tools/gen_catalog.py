"""Generates lib/animals/catalog_data.dart (docs/animals.md), notes_data.dart (docs/notes.md) and hints_data.dart (docs/hints.md).

Run from the repo root: python3 tools/gen_catalog.py && dart format lib/animals
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs/animals.md"
OUT = ROOT / "lib/animals/catalog_data.dart"
NOTES_DOC = ROOT / "docs/notes.md"
NOTES_OUT = ROOT / "lib/animals/notes_data.dart"
HINTS_DOC = ROOT / "docs/hints.md"
HINTS_OUT = ROOT / "lib/animals/hints_data.dart"
SOUNDS = ROOT / "assets/sounds"
SPRITES = ROOT / "assets/sprites"

HEAD_POINT = (24, 16)
STUB_FRAMES = ["stub_fox_1", "stub_fox_2"]
FALLBACK_SOUND = "yip"
HATS = [
    ("party-hat", "Party hat"),
    ("sombrero", "Sombrero"),
    ("beanie", "Beanie"),
    ("top-hat", "Top hat"),
    ("bowler-hat", "Bowler hat"),
]

BANDS = {
    "Day": "PartOfDay.day", "Twilight": "PartOfDay.twilight", "Night": "PartOfDay.night",
    "Brief": "LengthBand.brief", "Short": "LengthBand.short",
    "Medium length": "LengthBand.medium", "Long": "LengthBand.long",
    "Near": "DistanceBand.near", "Far": "DistanceBand.far",
    "Slow": "SpeedBand.slow", "Steady": "SpeedBand.steady", "Fast": "SpeedBand.fast",
}


def kebab(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def parse():
    lines = DOC.read_text().splitlines()
    bases, species = [], []
    section, current = None, None
    for line in lines:
        if line.startswith("## "):
            section = line[3:].strip()
            continue
        m = re.match(r"### (.+?) \(home: (.+)\)", line)
        if m:
            current = m.group(1)
            continue
        if not line.startswith("|") or line.startswith("|---") or line.startswith("| Base |") or line.startswith("| Species |"):
            continue
        c = cells(line)
        if section == "Bases":
            bases.append(c)
        elif section == "Species":
            species.append((current, c))
    return bases, species


def affinity_entries(cell, affinity):
    out = []
    cell = re.sub(r"\(.*?\)", "", cell).strip()
    if not cell:
        return out
    for token in cell.split(","):
        out.append((BANDS[token.strip()], affinity))
    return out


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def legends():
    rows, kind = [], None
    for line in DOC.read_text().splitlines():
        if line.startswith("## "):
            kind = "" if line[3:].strip() == "Legends" else None
            continue
        if kind is None:
            continue
        if line.startswith("### "):
            kind = "regional" if "Regional" in line else "base"
            continue
        if line.startswith("|") and not line.startswith("|---") and not line.startswith("| Legend |"):
            rows.append((kind, cells(line)))
    return rows


def entry_tree():
    base_rows, species_rows = parse()
    tree = {kebab(row[0]): {"name": row[0], "shapes": {}, "legends": []} for row in base_rows}
    for base_name, (name, _, _, _, colours) in species_rows:
        shape = kebab(re.sub(r"\s*\(.*\)", "", name))
        tree[kebab(base_name)]["shapes"][shape] = [
            kebab(re.match(r"(.+?) \d+%", t.strip()).group(1)) for t in colours.split(",") if t.strip()
        ]
    for _, row in legends():
        tree[kebab(row[1])]["legends"].append(kebab(row[0]))
    return tree


def note_rows():
    rows = {}
    for line in NOTES_DOC.read_text().splitlines():
        if not line.startswith("|"):
            continue
        c = cells(line)
        if len(c) == 3 and c[0] != "Id" and not set(c[0]) <= {"-", ":"}:
            rows[c[0]] = c[2]
    return rows


def write_notes(tree):
    notes = note_rows()
    ids = [e for base in tree.values() for s, cs in base["shapes"].items() for e in [s, *cs]]
    ids += [kebab(row[0]) for _, row in legends()]
    missing = [e for e in ids if e not in notes]
    if missing:
        raise SystemExit(f"docs/notes.md has no note for: {', '.join(missing)}")
    out = ["// Generated by tools/gen_catalog.py from docs/notes.md. Do not edit by hand.", "const Map<String, String> entryNotes = {"]
    out += [f"  {dart_str(e)}: {dart_str(notes[e])}," for e in ids]
    out += ["};", ""]
    NOTES_OUT.write_text("\n".join(out))


def riddle_rows():
    rows, inside = {}, False
    for line in HINTS_DOC.read_text().splitlines():
        if line.startswith("## "):
            inside = line[3:].strip().startswith("Riddles")
            continue
        if inside and line.startswith("|"):
            c = cells(line)
            if len(c) == 2 and c[0] != "Id" and not set(c[0]) <= {"-", ":"}:
                rows[c[0]] = c[1]
    return rows


def write_hints():
    riddles = riddle_rows()
    ids = [kebab(row[0]) for _, row in legends()]
    missing = [e for e in ids if e not in riddles]
    if missing:
        raise SystemExit(f"docs/hints.md has no riddle for: {', '.join(missing)}")
    out = ["// Generated by tools/gen_catalog.py from docs/hints.md. Do not edit by hand.", "const Map<String, String> legendRiddles = {"]
    out += [f"  {dart_str(e)}: {dart_str(riddles[e])}," for e in ids]
    out += ["};", ""]
    HINTS_OUT.write_text("\n".join(out))


def sound_for(name):
    return name if (SOUNDS / f"{name}.wav").exists() else FALLBACK_SOUND


def hat_sprite(hid):
    return f"hat_{hid}" if (SPRITES / f"hat_{hid}.png").exists() else "stub_hat"


def main():
    base_rows, species_rows = parse()
    habitat_of = {"meadow": "meadow", "river": "river", "sky": "sky"}
    out = [
        "// Generated by tools/gen_catalog.py from docs/animals.md. Do not edit by hand.",
        "import 'bands.dart';",
        "import 'catalog.dart';",
        "",
        f"const _frames = [{', '.join(dart_str(f) for f in STUB_FRAMES)}];",
        f"const _headPoints = [(x: {HEAD_POINT[0]}, y: {HEAD_POINT[1]}), (x: {HEAD_POINT[0]}, y: {HEAD_POINT[1]})];",
        "",
        "const _bases = <Base>[",
    ]
    for name, kinds, habitat, sound, arrival in base_rows:
        out += [
            "  Base(",
            f"    id: {dart_str(kebab(name))},",
            f"    name: {dart_str(name)},",
            f"    homeKinds: {{{', '.join(dart_str(k.strip()) for k in kinds.split(','))}}},",
            f"    habitat: Habitat.{habitat_of[habitat.split(',')[0].split()[0]]},",
            f"    sound: {dart_str(sound_for(sound))},",
            f"    bubble: {dart_str(sound + '!')},",
            f"    arrival: {dart_str(arrival)},",
            "    frames: _frames,",
            "    headPoints: _headPoints,",
            "  ),",
        ]
    out += ["];", "", "const _species = <Species>["]
    for base_name, (name, loves, likes, avoids, colours) in species_rows:
        also = re.search(r"\(also home on (.+?)\)", name)
        shape = re.sub(r"\s*\(.*\)", "", name)
        entries = (
            affinity_entries(loves, "Affinity.loves")
            + affinity_entries(likes, "Affinity.likes")
            + affinity_entries(avoids, "Affinity.avoids")
        )
        out += [
            "  Species(",
            f"    id: {dart_str(kebab(shape))},",
            f"    name: {dart_str(shape)},",
            f"    baseId: {dart_str(kebab(base_name))},",
        ]
        if entries:
            out.append(f"    affinities: {{{', '.join(f'{b}: {a}' for b, a in entries)}}},")
        if also:
            out.append(f"    alsoHomeKinds: {{{', '.join(dart_str(k.strip()) for k in also.group(1).split(','))}}},")
        if colours:
            parts = []
            for token in colours.split(","):
                cm = re.match(r"(.+?) (\d+)%", token.strip())
                parts.append(
                    f"ColourSpecies(id: {dart_str(kebab(cm.group(1)))}, name: {dart_str(cm.group(1))}, "
                    f"shapeSpeciesId: {dart_str(kebab(shape))}, chance: {int(cm.group(2)) / 100})"
                )
            out.append(f"    colours: [{', '.join(parts)}],")
        out.append("  ),")
    out += ["];", "", "const _legends = <Legend>["]
    for kind, row in legends():
        out += [
            "  Legend(",
            f"    id: {dart_str(kebab(row[0]))},",
            f"    name: {dart_str(row[0])},",
            f"    baseId: {dart_str(kebab(row[1]))},",
        ]
        if kind == "base":
            out.append(f"    likes: {BANDS[row[2]]},")
        else:
            prefix = re.fullmatch(r"every time zone starting with (\S+)", row[2])
            if prefix:
                out.append(f"    regionPrefix: {dart_str(prefix.group(1))},")
            else:
                zones = ", ".join(dart_str(z.strip()) for z in row[2].split(","))
                out.append(f"    regionZones: {{{zones}}},")
        out.append("  ),")
    out += ["];", "", "const _hats = <Hat>["]
    for hid, hname in HATS:
        out.append(f"  Hat(id: {dart_str(hid)}, name: {dart_str(hname)}, sprite: {dart_str(hat_sprite(hid))}),")
    out += ["];", "", "final Catalog defaultCatalog = Catalog(bases: _bases, species: _species, legends: _legends, hats: _hats);", ""]
    OUT.write_text("\n".join(out))
    write_notes(entry_tree())
    write_hints()


if __name__ == "__main__":
    main()
