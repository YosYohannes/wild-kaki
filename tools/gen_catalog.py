"""Generates lib/animals/catalog_data.dart from docs/animals.md.

Run from the repo root: python3 tools/gen_catalog.py && dart format lib/animals/catalog_data.dart
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs/animals.md"
OUT = ROOT / "lib/animals/catalog_data.dart"

HEAD_POINT = (24, 16)
STUB_FRAMES = ["stub_fox_1", "stub_fox_2"]
STUB_SOUND = "yip"
HATS = [
    ("party-hat", "Party hat"),
    ("sombrero", "Sombrero"),
    ("beanie", "Beanie"),
    ("top-hat", "Top hat"),
    ("flower-crown", "Flower crown"),
]

BANDS = {
    "Day": "PartOfDay.day", "Twilight": "PartOfDay.twilight", "Night": "PartOfDay.night",
    "Brief": "LengthBand.brief", "Short": "LengthBand.short",
    "Medium length": "LengthBand.medium", "Long": "LengthBand.long",
    "Near": "DistanceBand.near", "Far": "DistanceBand.far",
    "Slow": "SpeedBand.slow", "Steady": "SpeedBand.steady", "Fast": "SpeedBand.fast",
}


def kebab(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def parse():
    lines = DOC.read_text().splitlines()
    bases, species = [], []
    section, current = None, None
    for line in lines:
        if line.startswith("## "):
            section = line[3:].strip()
            continue
        m = re.match(r"### (.+?) \(home: (.+)\)", line)
        if m:
            current = m.group(1)
            continue
        if not line.startswith("|") or line.startswith("|---") or line.startswith("| Base |") or line.startswith("| Species |"):
            continue
        c = cells(line)
        if section == "Bases":
            bases.append(c)
        elif section == "Species":
            species.append((current, c))
    return bases, species


def affinity_entries(cell, affinity):
    out = []
    cell = re.sub(r"\(.*?\)", "", cell).strip()
    if not cell:
        return out
    for token in cell.split(","):
        out.append((BANDS[token.strip()], affinity))
    return out


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main():
    base_rows, species_rows = parse()
    habitat_of = {"meadow": "meadow", "river": "river", "sky": "sky"}
    out = [
        "// Generated by tools/gen_catalog.py from docs/animals.md. Do not edit by hand.",
        "import 'bands.dart';",
        "import 'catalog.dart';",
        "",
        f"const _frames = [{', '.join(dart_str(f) for f in STUB_FRAMES)}];",
        f"const _headPoints = [(x: {HEAD_POINT[0]}, y: {HEAD_POINT[1]}), (x: {HEAD_POINT[0]}, y: {HEAD_POINT[1]})];",
        "",
        "const _bases = <Base>[",
    ]
    for name, kinds, habitat, sound, arrival in base_rows:
        out += [
            "  Base(",
            f"    id: {dart_str(kebab(name))},",
            f"    name: {dart_str(name)},",
            f"    homeKinds: {{{', '.join(dart_str(k.strip()) for k in kinds.split(','))}}},",
            f"    habitat: Habitat.{habitat_of[habitat.split(',')[0].split()[0]]},",
            f"    sound: {dart_str(STUB_SOUND)},",
            f"    bubble: {dart_str(sound + '!')},",
            f"    arrival: {dart_str(arrival)},",
            "    frames: _frames,",
            "    headPoints: _headPoints,",
            "  ),",
        ]
    out += ["];", "", "const _species = <Species>["]
    for base_name, (name, loves, likes, avoids, colours) in species_rows:
        also = re.search(r"\(also home on (.+?)\)", name)
        shape = re.sub(r"\s*\(.*\)", "", name)
        entries = (
            affinity_entries(loves, "Affinity.loves")
            + affinity_entries(likes, "Affinity.likes")
            + affinity_entries(avoids, "Affinity.avoids")
        )
        out += [
            "  Species(",
            f"    id: {dart_str(kebab(shape))},",
            f"    name: {dart_str(shape)},",
            f"    baseId: {dart_str(kebab(base_name))},",
        ]
        if entries:
            out.append(f"    affinities: {{{', '.join(f'{b}: {a}' for b, a in entries)}}},")
        if also:
            out.append(f"    alsoHomeKinds: {{{', '.join(dart_str(k.strip()) for k in also.group(1).split(','))}}},")
        if colours:
            parts = []
            for token in colours.split(","):
                cm = re.match(r"(.+?) (\d+)%", token.strip())
                parts.append(
                    f"ColourSpecies(id: {dart_str(kebab(cm.group(1)))}, name: {dart_str(cm.group(1))}, "
                    f"shapeSpeciesId: {dart_str(kebab(shape))}, chance: {int(cm.group(2)) / 100})"
                )
            out.append(f"    colours: [{', '.join(parts)}],")
        out.append("  ),")
    out += ["];", "", "const _hats = <Hat>["]
    for hid, hname in HATS:
        out.append(f"  Hat(id: {dart_str(hid)}, name: {dart_str(hname)}, sprite: 'stub_hat'),")
    out += ["];", "", "final Catalog defaultCatalog = Catalog(bases: _bases, species: _species, hats: _hats);", ""]
    OUT.write_text("\n".join(out))


if __name__ == "__main__":
    main()
